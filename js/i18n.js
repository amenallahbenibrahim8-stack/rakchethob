const escapedKeys = [...translations.keys()].sort((a, b) => b.length - a.length)
  .map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
const textPattern = new RegExp(`(^|[^\\p{L}\\p{N}_])(${escapedKeys.join("|")})(?=$|[^\\p{L}\\p{N}_])`, "giu");

export function translateText(value) {
  return String(value).replace(/\bCoupleZone\b/gi, "ركشة حب")
    .replace(textPattern, (match, prefix, key) => `${prefix}${translations.get([...translations.keys()].find((item) => item.toLowerCase() === key.toLowerCase()))}`);
}

export function localize(root = document) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => node.parentElement?.closest("script,style,code,pre") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const translated = translateText(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }
  root.querySelectorAll?.("[placeholder],[aria-label],[title],img[alt]").forEach((element) => {
    for (const attribute of ["placeholder", "aria-label", "title", "alt"]) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, translateText(element.getAttribute(attribute)));
    }
  });
}

if (typeof document !== "undefined") {
  document.documentElement.lang = "ar-TN";
  document.documentElement.dir = "rtl";
  localize(document);
  new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") localize(record.target.parentElement);
      for (const node of record.addedNodes) if (node.nodeType === Node.ELEMENT_NODE) localize(node);
    }
  }).observe(document.documentElement, { subtree: true, childList: true, characterData: true });
}
